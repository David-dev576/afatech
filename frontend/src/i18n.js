function initialLocale() {
  const saved = localStorage.getItem('afa_lang')
  if (SUPPORTED.includes(saved)) return saved
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'fr'
}

export const locale = ref(initialLocale())
document.documentElement.lang = locale.value

export function setLocale(lang) {
  if (!SUPPORTED.includes(lang)) return
  locale.value = lang
  localStorage.setItem('afa_lang', lang)
  document.documentElement.lang = lang
}

// Renvoie le texte de la langue active. Repli sur le français si une clé manque.
export function t(key) {
  const dict = messages[locale.value] || messages.fr
  return dict[key] ?? messages.fr[key] ?? key
}